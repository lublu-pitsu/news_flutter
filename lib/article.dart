class Article {
  final String id;
  final String title;
  final String summary;
  final String image;
  final String source;
  final String url;
  final DateTime date;

  Article({
    required this.id,
    required this.title,
    required this.summary,
    required this.image,
    required this.source,
    required this.url,
    required this.date,
  });
}
